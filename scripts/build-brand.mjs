#!/usr/bin/env node
// Build every brand asset from the SVG masters in brand/src plus site.json:
//
//   brand/logo/            PRIMARY mark (circle · triangle · Venn, made by scripts/make-aa-mark.mjs):
//                          colour / plain (no words) / mono / reversed / white SVG, PNG 256–4096 px,
//                          vector PDF, horizontal & stacked wordmarks with the type outlined
//   brand/alt-weave/logo/  ALTERNATE mark (the three woven triangles) — same file set
//   brand/favicon/         favicon.ico, icon.svg, apple-touch-icon, 192/512 and maskable icons (primary, plain)
//   brand/qr/              QR codes for the Zoom link, the website (EN and /es/) and /join/ (SVG + 1200 px PNG)
//   brand/social/          1200×630 Open Graph cards (EN/ES) and a 1080×1080 square
//   brand/BRAND.md         colours, fonts, file list and usage notes
//   (brand/flyer/          the committee's OFFICIAL flyer, PDF + JPG/WebP — supplied by hand,
//                          NOT generated or touched by this script; brand/poster/ is made by pdf.mjs)
//
// Libraries: @resvg/resvg-js (SVG → PNG), node-qrcode, pdfkit + svg-to-pdfkit (vector PDF),
// opentype.js + wawoff2 (fonts → outlines), png-to-ico. Deterministic (no build dates inside): the
// files are committed AND regenerated by every CI build (so the QR codes always follow site.json).
// Card text follows the site: ET first ("11:00 AM – 7:00 PM ET"), then "8:00 AM PT · 9:00 AM MT · 10:00 AM CT".
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import QRCode from "qrcode";
import PDFDocument from "pdfkit";
import SVGtoPDF from "svg-to-pdfkit";
import pngToIco from "png-to-ico";
import { root, loadFont, textPath, textWidth, centered, fitSize, wrap } from "./lib/text.mjs";
import { applyTokens } from "./lib/tokens.mjs";

const site = JSON.parse(fs.readFileSync(path.join(root, "src/_data/site.json"), "utf8"));
const { default: when } = await import(pathToFileURL(path.join(root, "src/_data/when.js")).href);
let i18n = null;
try { i18n = JSON.parse(fs.readFileSync(path.join(root, "src/_data/i18n.json"), "utf8")); } catch { /* not written yet */ }
// A string from i18n.json (lang, dotted path) with its {tokens} filled in, or the fallback.
const tr = (lang, keyPath, fallback = "") => {
  const v = keyPath.split(".").reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), i18n && i18n[lang]);
  return typeof v === "string" && v.trim() ? applyTokens(v, { site, when }) : fallback;
};

const INK = site.brand.ink, PAPER = site.brand.paper, MUTED = "#5B5F73";
const [RECOVERY, UNITY, SERVICE] = site.legacies.map((l) => l.color);
const BRAND = path.join(root, "brand");
const out = (...p) => { const f = path.join(BRAND, ...p); fs.mkdirSync(path.dirname(f), { recursive: true }); return f; };
const written = [];
const write = (file, data) => { fs.writeFileSync(file, data); written.push(path.relative(BRAND, file).replace(/\\/g, "/")); };
// A fixed date keeps the logo/wordmark PDFs (the only PDFs made here) byte-identical between builds.
// It is the date the marks were drawn: do NOT tie it to zoom.lastUpdated, or every Zoom edit rewrites
// the logo files (their CreationDate and /ID would change although the artwork did not).
const STAMP = new Date("2026-10-04T12:00:00Z");

// ---------- fonts ----------
const fontDisplay = await loadFont("@fontsource/fraunces/files/fraunces-latin-600-normal.woff2");
const fontDisplayItalic = await loadFont("@fontsource/fraunces/files/fraunces-latin-400-italic.woff2");
const fontBody = await loadFont("@fontsource/inter/files/inter-latin-500-normal.woff2");
const fontBodyBold = await loadFont("@fontsource/inter/files/inter-latin-700-normal.woff2");

// ---------- helpers ----------
const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/i, "").replace(/<\/svg>\s*$/i, "").trim();
const vb = (svg) => ((svg.match(/viewBox="([^"]+)"/) || [])[1] || "0 0 1024 1024").split(/\s+/).map(Number);
const svgDoc = (w, h, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">${body}</svg>`;
const recolor = (svg, from, to) => svg.split(from).join(to).split(from.toLowerCase()).join(to);
const placeMark = (svg, x, y, size) => { const [, , w] = vb(svg); return `<g transform="translate(${x} ${y}) scale(${(size / w).toFixed(5)})">${inner(svg)}</g>`; };
const png = (svg, width, background) => new Resvg(svg, { fitTo: { mode: "width", value: width }, background, font: { loadSystemFonts: false } }).render().asPng();
function pdf(svg, file, title) {
  const [, , w, h] = vb(svg);
  const scale = 512 / Math.max(w, h); // ≈ 7 in on the long side; it is vector anyway
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: [w * scale, h * scale], margin: 0, info: { Title: title, Author: site.contact.committee, Subject: site.title, CreationDate: STAMP, ModDate: STAMP } });
    const stream = fs.createWriteStream(file);
    doc.pipe(stream);
    SVGtoPDF(doc, svg, 0, 0, { width: w * scale, height: h * scale, assumePt: true });
    doc.end();
    stream.on("finish", () => { written.push(path.relative(BRAND, file).replace(/\\/g, "/")); resolve(); });
    stream.on("error", reject);
  });
}
const readSrc = (rel) => (fs.existsSync(path.join(BRAND, "src", rel)) ? fs.readFileSync(path.join(BRAND, "src", rel), "utf8").trim() : null);

// ---------- the two marks ----------
const SETS = [
  { dir: "logo", title: "Primary mark — circle, triangle and Venn", mark: readSrc("mark.svg"), mono: readSrc("mark-mono.svg"), plain: readSrc("mark-plain.svg"), plainMono: readSrc("mark-plain-mono.svg") },
  { dir: "alt-weave/logo", title: "Alternate mark — three woven triangles", mark: readSrc("weave/mark.svg"), mono: readSrc("weave/mark-mono.svg") },
].filter((s) => s.mark && s.mono);

function horizontal(mark, { ink = INK, muted = MUTED } = {}) {
  const H = 1024, titleSize = 290, tagSize = 84, gap = 90;
  const title = site.name, tag = site.tagline;
  const textW = Math.max(textWidth(fontDisplay, title, titleSize), textWidth(fontBody, tag, tagSize));
  const W = Math.ceil(H + gap + textW + 30), x = H + gap;
  return svgDoc(W, H, `${placeMark(mark, 0, 0, H)}${textPath(fontDisplay, title, x, 548, titleSize, ink)}${textPath(fontBody, tag, x + 6, 690, tagSize, muted)}`);
}
function stacked(mark, { ink = INK, muted = MUTED } = {}) {
  const titleSize = 190, tagSize = 58, markSize = 900;
  const title = site.name, tag = site.tagline;
  const W = Math.ceil(Math.max(markSize, textWidth(fontDisplay, title, titleSize), textWidth(fontBody, tag, tagSize)) + 160);
  const H = markSize + 60 + titleSize + 40 + tagSize + 70, cx = W / 2;
  return svgDoc(W, H, `${placeMark(mark, cx - markSize / 2, 0, markSize)}${centered(fontDisplay, title, cx, markSize + 60 + titleSize * 0.72, titleSize, ink)}${centered(fontBody, tag, cx, markSize + 60 + titleSize + 40 + tagSize * 0.75, tagSize, muted)}`);
}

for (const set of SETS) {
  const D = set.dir;
  const reversed = recolor(set.mono, INK, PAPER), white = recolor(set.mono, INK, "#FFFFFF");
  write(out(D, "mark.svg"), set.mark);
  write(out(D, "mark-mono.svg"), set.mono);
  write(out(D, "mark-reversed.svg"), reversed);
  write(out(D, "mark-white.svg"), white);
  for (const size of [256, 512, 1024, 2048, 4096]) write(out(D, `mark-${size}.png`), png(set.mark, size));
  write(out(D, "mark-2048-white-bg.png"), png(set.mark, 2048, "#FFFFFF"));
  write(out(D, "mark-2048-cream-bg.png"), png(set.mark, 2048, PAPER));
  write(out(D, "mark-mono-2048.png"), png(set.mono, 2048));
  write(out(D, "mark-reversed-2048-on-ink.png"), png(reversed, 2048, INK));
  write(out(D, "mark-white-2048.png"), png(white, 2048));
  await pdf(set.mark, out(D, "mark.pdf"), `${site.name} — ${set.title}`);
  await pdf(set.mono, out(D, "mark-mono.pdf"), `${site.name} — ${set.title} (one colour)`);
  if (set.plain) {
    const plainReversed = recolor(set.plainMono || set.mono, INK, PAPER);
    write(out(D, "mark-plain.svg"), set.plain);
    if (set.plainMono) write(out(D, "mark-plain-mono.svg"), set.plainMono);
    write(out(D, "mark-plain-reversed.svg"), plainReversed);
    for (const size of [256, 512, 1024, 2048]) write(out(D, `mark-plain-${size}.png`), png(set.plain, size));
    if (set.plainMono) write(out(D, "mark-plain-mono-1024.png"), png(set.plainMono, 1024));
    write(out(D, "mark-plain-reversed-1024-on-ink.png"), png(plainReversed, 1024, INK));
    await pdf(set.plain, out(D, "mark-plain.pdf"), `${site.name} — ${set.title} (no words)`);
  }
  // wordmarks: the horizontal lockup uses the plain mark when there is one (it is small next to the text)
  const hMark = set.plain || set.mark, hMono = set.plainMono || set.mono;
  const lockups = {
    "wordmark-horizontal": horizontal(hMark),
    "wordmark-horizontal-mono": horizontal(hMono),
    "wordmark-horizontal-reversed": horizontal(recolor(hMono, INK, PAPER), { ink: PAPER, muted: "#C9CBD6" }),
    "wordmark-stacked": stacked(set.mark),
    "wordmark-stacked-mono": stacked(set.mono),
    "wordmark-stacked-reversed": stacked(reversed, { ink: PAPER, muted: "#C9CBD6" }),
  };
  for (const [name, svg] of Object.entries(lockups)) {
    const dark = name.endsWith("reversed");
    write(out(D, `${name}.svg`), svg);
    write(out(D, `${name}-2000.png`), png(svg, 2000, dark ? INK : undefined));
    write(out(D, `${name}-4000.png`), png(svg, 4000, dark ? INK : undefined));
    await pdf(dark ? svg.replace(/<svg([^>]*)>/, `<svg$1><rect width="100%" height="100%" fill="${INK}"/>`) : svg, out(D, `${name}.pdf`), `${site.name} — ${name}`);
  }
}

// ---------- favicons & app icons (primary mark, plain version) ----------
const primary = SETS[0];
const iconMark = primary.plain || primary.mark;
const [, , MW, MH] = vb(iconMark);
const framed = (mark, scale, bg) => svgDoc(MW, MH, `${bg ? `<rect width="${MW}" height="${MH}" fill="${bg}"/>` : ""}${placeMark(mark, (MW * (1 - scale)) / 2, (MH * (1 - scale)) / 2, MW * scale)}`);
write(out("favicon/icon.svg"), iconMark);
const ico = await pngToIco([png(iconMark, 16), png(iconMark, 32), png(iconMark, 48)]);
write(out("favicon/favicon.ico"), ico);
fs.writeFileSync(path.join(root, "src/favicon.ico"), ico);
write(out("favicon/favicon-32.png"), png(iconMark, 32));
write(out("favicon/favicon-16.png"), png(iconMark, 16));
write(out("favicon/apple-touch-icon.png"), png(framed(iconMark, 0.84, PAPER), 180));
write(out("favicon/icon-192.png"), png(framed(iconMark, 0.88, PAPER), 192));
write(out("favicon/icon-512.png"), png(framed(iconMark, 0.88, PAPER), 512));
write(out("favicon/maskable-512.png"), png(framed(iconMark, 0.62, PAPER), 512));

// ---------- QR codes ----------
// site-es → the Spanish home page, for the Spanish printable poster (/es/flyer/#printable-poster).
const qrTargets = { zoom: site.event.zoom.joinUrl, site: site.url, "site-es": `${site.url}/es/`, join: `${site.url}/join/` };
for (const [key, text] of Object.entries(qrTargets)) {
  const svg = await QRCode.toString(text, { type: "svg", errorCorrectionLevel: "M", margin: 1, color: { dark: INK, light: "#0000" } });
  write(out(`qr/qr-${key}.svg`), svg.replace(/<svg /, `<svg role="img" aria-label="QR code" `));
  write(out(`qr/qr-${key}.png`), await QRCode.toBuffer(text, { type: "png", errorCorrectionLevel: "M", width: 1200, margin: 2, color: { dark: INK, light: "#FFFFFF" } }));
}

// ---------- social cards (primary mark) ----------
// The sub-line is the flyer's ("How the Steps, Traditions and Concepts weave …"): site.subtitle (EN) and
// i18n.es.landing.subline (ES) — NOT site.tagline, which belongs to the wordmark lockups above.
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
// when.js glues each time together with no-break spaces and a word joiner after the dash (for the web
// pages); the cards are laid out by hand from plain words, so turn them back into ordinary spaces.
const plain = (s) => String(s ?? "").replace(/\u2060/g, "").replace(/[\u00A0\u202F]/g, " ");
const cardText = (lang) => {
  const es = lang === "es";
  const c = {
    eyebrow: (es ? tr("es", "landing.eyebrow", "Un taller de A.A. en línea de un día") : tr("en", "landing.eyebrow", "A 1-day online A.A. workshop")).toUpperCase(),
    sub: es ? tr("es", "landing.subline", site.subtitle || "") : site.subtitle || tr("en", "landing.subline", ""),
    date: es ? cap(when.date.longEs) : when.date.long,
    // Same precision on both lines, like the flyer and the site: "11:00 AM – 7:00 PM ET" over "8:00 AM PT · …".
    // Spanish spells the zone out ("…, hora del Este (ET)") for readers outside the U.S., like the Spanish poster.
    time: es ? when.time.leadLongEs : when.time.lead, // 11:00 AM – 7:00 PM ET
    also: es ? when.time.startsAlsoEs : when.time.startsAlso, // 8:00 AM PT · 9:00 AM MT · 10:00 AM CT
    where: [tr(lang, "labels.online", es ? "En línea por Zoom" : "Online on Zoom"), tr(lang, "labels.interpretationBadge", es ? "Interpretación en español y en ASL" : "Spanish & ASL interpretation"), tr(lang, "labels.free", es ? "Gratuito" : "Free")].join(" · "),
  };
  for (const k of Object.keys(c)) c[k] = plain(c[k]);
  return c;
};
function ogCard(lang) {
  const c = cardText(lang);
  const W = 1200, H = 630, x = 540, maxW = W - x - 60;
  let y = 150, body = `<rect width="${W}" height="${H}" fill="${PAPER}"/>`;
  body += `<rect width="${W / 3}" height="14" fill="${RECOVERY}"/><rect x="${W / 3}" width="${W / 3}" height="14" fill="${UNITY}"/><rect x="${(2 * W) / 3}" width="${W / 3}" height="14" fill="${SERVICE}"/>`;
  body += `<defs><pattern id="weave" width="22" height="22" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="2" height="22" fill="${RECOVERY}" opacity="0.07"/></pattern></defs><rect y="14" width="${W}" height="${H - 14}" fill="url(#weave)"/>`;
  body += placeMark(primary.mark, 60, 105, 420);
  body += textPath(fontBodyBold, c.eyebrow, x, y, fitSize(fontBodyBold, c.eyebrow, maxW, 24, 16, { letterSpacing: 0.12 }), MUTED, { letterSpacing: 0.12 });
  y += 80;
  body += textPath(fontDisplay, site.name, x, y, fitSize(fontDisplay, site.name, maxW, 72, 40), INK);
  // At most two sub-lines (30 px if 33 px would need a third), so the date block always fits above the domain.
  let subSize = 33, subLines = wrap(fontDisplayItalic, c.sub, subSize, maxW);
  if (subLines.length > 2) { subSize = 28; subLines = wrap(fontDisplayItalic, c.sub, subSize, maxW).slice(0, 2); }
  for (const line of subLines) { y += subSize + 12; body += textPath(fontDisplayItalic, line, x, y, subSize, "#3F4358"); }
  y += 58;
  body += textPath(fontBodyBold, c.date, x, y, fitSize(fontBodyBold, c.date, maxW, 30, 20), RECOVERY); y += 38;
  body += textPath(fontBodyBold, c.time, x, y, fitSize(fontBodyBold, c.time, maxW, 28, 20), INK); y += 32;
  body += textPath(fontBody, c.also, x, y, fitSize(fontBody, c.also, maxW, 22, 16), MUTED); y += 34;
  body += textPath(fontBody, c.where, x, y, fitSize(fontBody, c.where, maxW, 22, 16), MUTED);
  body += textPath(fontDisplay, site.domain, x, H - 40, 38, RECOVERY);
  return svgDoc(W, H, body);
}
write(out("social/og.svg"), ogCard("en"));
write(out("social/og.png"), png(ogCard("en"), 1200));
write(out("social/og-es.svg"), ogCard("es"));
write(out("social/og-es.png"), png(ogCard("es"), 1200));
// The website's own link-preview cards (src/assets/img/og*.png) are the flyer-style ones made by
// scripts/make-og.mjs (npm run brand:og); these light cards stay in brand/social/ for other uses.

// wrap() with even line lengths: the narrowest width that still gives the same number of lines
// (so a centred two-line sub-line never ends on one orphaned word).
function wrapBalanced(font, text, size, maxW) {
  const n = wrap(font, text, size, maxW).length;
  let lo = maxW / 2, hi = maxW;
  for (let i = 0; i < 24; i++) { const mid = (lo + hi) / 2; if (wrap(font, text, size, mid).length > n) lo = mid; else hi = mid; }
  return wrap(font, text, size, hi);
}
function square() {
  const c = cardText("en");
  const S = 1080, cx = S / 2, maxW = S - 140;
  let body = `<rect width="${S}" height="${S}" fill="${PAPER}"/>`;
  body += `<rect width="${S / 3}" height="16" fill="${RECOVERY}"/><rect x="${S / 3}" width="${S / 3}" height="16" fill="${UNITY}"/><rect x="${(2 * S) / 3}" width="${S / 3}" height="16" fill="${SERVICE}"/>`;
  body += placeMark(primary.mark, cx - 220, 64, 440);
  body += centered(fontBodyBold, c.eyebrow, cx, 580, fitSize(fontBodyBold, c.eyebrow, maxW, 26, 18, { letterSpacing: 0.12 }), MUTED, { letterSpacing: 0.12 });
  body += centered(fontDisplay, site.name, cx, 668, fitSize(fontDisplay, site.name, maxW, 78, 44), INK);
  let y = 724;
  for (const line of wrapBalanced(fontDisplayItalic, c.sub, 32, maxW).slice(0, 2)) { body += centered(fontDisplayItalic, line, cx, y, 32, "#3F4358"); y += 44; }
  y += 22;
  body += centered(fontBodyBold, c.date, cx, y, fitSize(fontBodyBold, c.date, maxW, 34, 24), RECOVERY); y += 44;
  const detail = `${c.time} · Zoom · ${tr("en", "labels.interpretationValue", "Spanish · ASL").replace(" · ", " & ")}`;
  body += centered(fontBodyBold, detail, cx, y, fitSize(fontBodyBold, detail, maxW, 28, 20), INK); y += 38;
  body += centered(fontBody, c.also, cx, y, fitSize(fontBody, c.also, maxW, 24, 18), MUTED);
  body += centered(fontDisplay, site.domain, cx, S - 52, 42, RECOVERY);
  return svgDoc(S, S, body);
}
write(out("social/square.svg"), square());
write(out("social/square.png"), png(square(), 1080));

